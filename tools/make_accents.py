#!/usr/bin/env python3
"""Writes web/accents.css: every rule of web/maycon.css that uses the red accent, once per other profile color.

    python3 tools/make_accents.py

Run it after changing a red in maycon.css (#E5484D, #FF7A7F or rgba(229, 72, 77, ...)).
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PALETTE = {'pink': ('#EC4899', '#F9A8D4', '236, 72, 153'), 'blue': ('#3B82F6', '#7FB0FF', '59, 130, 246'),
           'green': ('#22C55E', '#6EE7A0', '34, 197, 94'),
           'purple': ('#8B5CF6', '#B9A0FF', '139, 92, 246'), 'orange': ('#F97316', '#FFAB70', '249, 115, 22'),
           'yellow': ('#FFE100', '#FFE97A', '255, 225, 0')}
RED = ('#E5484D', '#FF7A7F', '229, 72, 77')


def main():
    with open(os.path.join(ROOT, 'web', 'maycon.css'), encoding='utf-8') as f:
        css = re.sub(r'/\*.*?\*/', '', f.read(), flags=re.S)
    out = ['/* Generated by tools/make_accents.py from maycon.css: the red accent per profile color (body.accent-*). */']
    for name, colors in PALETTE.items():
        for selector, body in re.findall(r'([^{}@]+)\{([^{}]*)\}', css):
            decls = [d.strip() for d in body.split(';') if d.strip()]
            red = [d for d in decls if any(c in d for c in RED)]
            if not red:
                continue
            new = red
            for old, color in zip(RED, colors):
                new = [d.replace(old, color) for d in new]
            # Brand rule from the Athos sites: text on yellow is #1D1D1B, never white.
            if name == 'yellow' and any(d.startswith('background') and RED[0] in d for d in decls):
                new.append('color: #1D1D1B')
            scoped = []
            for s in selector.split(','):
                s = s.strip()
                scoped.append('body.accent-%s%s%s' % (name, '' if s.startswith('.night') else ' ', s))
            out.append('%s { %s; }' % (', '.join(scoped), '; '.join(new)))
    with open(os.path.join(ROOT, 'web', 'accents.css'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('Wrote web/accents.css (%d rules).' % (len(out) - 1))


if __name__ == '__main__':
    main()
